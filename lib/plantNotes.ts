// 긴 이름부터 맞춰야 "레몬타임"이 "레몬"으로 넘어가지 않는다.
const KEYS = Object.keys(NOTES).sort((a, b) => b.length - a.length);

export function noteFor(name: string, category?: string): PlantNote | null {
  const plain = (name ?? "").replace(/\s/g, "");
  const hit = KEYS.find((key) => plain.includes(key));
  if (hit) return NOTES[hit];

  const categoryHit = Object.keys(BY_CATEGORY).find((key) => (category ?? "").includes(key));
  return categoryHit ? BY_CATEGORY[categoryHit] : null;
}
